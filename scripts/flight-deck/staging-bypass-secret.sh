#!/usr/bin/env bash
# Stores the Vercel "Protection Bypass for Automation" value for the Flight
# Deck SYNTHETIC STAGING project in AWS Secrets Manager (tiro-stage,
# us-east-1). Run it in AWS CloudShell from a checkout of this repository:
#
#   bash scripts/flight-deck/staging-bypass-secret.sh create    # first time
#   bash scripts/flight-deck/staging-bypass-secret.sh rotate    # new value
#
# The value is pasted at a silent prompt and handed to the AWS CLI only on
# its standard input (--secret-string file:///dev/stdin). It is never
# written to a file, never placed on a command line (printf is a shell
# builtin, so no process ever has it as an argument), never traced, and
# never printed: the only output is the secret's ARN and version ID. The
# variable lives only in a subshell and is unset after use, and in every
# outcome when the subshell ends. Never add --debug: it would log the
# request body. Docs: docs/flight-deck/staging-setup.md §10.3 and §10.7.
set -uo pipefail

readonly NAME="tiro-flight-deck-staging/vercel-automation-bypass"
readonly REGION="us-east-1"
# The staging account (tiro-stage). Checked before you are asked for the value.
readonly EXPECTED_ACCOUNT="821507736007"
readonly DESCRIPTION="Vercel Protection Bypass for Automation, staging project tiro-flight-deck-staging"

mode="${1:-}"
case "$mode" in
  create | rotate) ;;
  *)
    echo "usage: $0 create|rotate" >&2
    exit 2
    ;;
esac

# Refuse to run anywhere but tiro-stage, before the value is ever entered.
account=$(aws sts get-caller-identity --region "$REGION" --no-cli-pager --query Account --output text) || {
  echo "STOP: could not confirm the AWS account (are you signed in?). Nothing was stored." >&2
  exit 1
}
if [ "$account" != "$EXPECTED_ACCOUNT" ]; then
  echo "STOP: signed in to AWS account $account, not tiro-stage ($EXPECTED_ACCOUNT). Nothing was stored." >&2
  exit 1
fi
echo "AWS account $account (tiro-stage), region $REGION." >&2

(
  # Nothing below may be traced or echoed, whatever the calling shell does.
  set +o xtrace +o verbose
  trap 'unset -v V' EXIT
  if [ "$mode" = create ]; then prompt="Paste the Vercel bypass secret, then press Enter: "; else prompt="Paste the NEW Vercel bypass secret, then press Enter: "; fi
  IFS= read -rs -p "$prompt" V || { echo >&2; echo "No input. Nothing was stored." >&2; exit 1; }
  echo >&2
  # A Vercel-generated bypass secret uses URL-safe characters only. Anything
  # else (empty, a space, a quote, a line break) is refused, not escaped.
  [[ "$V" =~ ^[A-Za-z0-9_-]{16,}$ ]] || { echo "Refused: empty or unexpected format. Nothing was stored." >&2; exit 1; }
  if [ "$mode" = create ]; then
    printf '%s' "$V" | aws secretsmanager create-secret --region "$REGION" --no-cli-pager \
      --name "$NAME" --description "$DESCRIPTION" \
      --secret-string file:///dev/stdin \
      --query '{Arn:ARN,VersionId:VersionId}' --output table
  else
    printf '%s' "$V" | aws secretsmanager put-secret-value --region "$REGION" --no-cli-pager \
      --secret-id "$NAME" \
      --secret-string file:///dev/stdin \
      --query '{Arn:ARN,VersionId:VersionId}' --output table
  fi
  rc=$?
  unset -v V
  exit "$rc"
)
